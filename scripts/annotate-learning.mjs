function annotate(filename, rules, title, mode='js') {
  const comment = (indent,text) => indent + (mode==='html' ? `<!-- [학습] ${text} -->` : mode==='css' ? `/* [학습] ${text} */` : `// [학습] ${text}`);
  const source = strip(fs.readFileSync(filename,'utf8'));
  const output = [comment('',title)];
  for(const line of source.split('\n')) {
    const trimmed=line.trim();
    const found=rules.find(([prefix])=>trimmed.startsWith(prefix));
    const indent=line.match(/^\s*/)[0];
    if(found) output.push(comment(indent,found[1]));
    else if(mode==='js' && trimmed.startsWith('import ')) output.push(comment(indent,'import로 다른 파일의 기능을 가져옵니다. { ... } 안의 이름은 해당 파일이 export한 이름입니다.'));
    else if(mode==='js' && trimmed.startsWith('export ')) output.push(comment(indent,'이 파일의 함수를 외부에서 import할 수 있도록 공개합니다.'));
    output.push(line);
  }
  fs.writeFileSync(filename,output.join('\n'));
}
